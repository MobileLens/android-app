/** Shown in place of the gallery when a phone has no photos yet. */
@Composable
fun GalleryEmptyState(modifier: Modifier = Modifier) {
    Column(
        modifier = modifier.padding(24.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.Center,
    ) {
        PhotoPlaceholder(modifier = Modifier.size(72.dp))
        Text(
            text = stringResource(R.string.gallery_empty),
            modifier = Modifier.padding(top = 16.dp),
            style = MaterialTheme.typography.titleMedium,
            color = MaterialTheme.colorScheme.onSurface,
        )
        Text(
            text = stringResource(R.string.gallery_empty_supporting),
            modifier = Modifier.padding(top = 4.dp),
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
        )
    }
}

@Preview(showBackground = true)
@Composable
private fun GalleryEmptyStatePreview() {
    MaterialTheme {
        GalleryEmptyState(modifier = Modifier.fillMaxWidth())
    }
}
